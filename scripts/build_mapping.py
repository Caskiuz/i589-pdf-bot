"""Construye config/i589_mapping.json: diccionario llave lógica -> campo Adobe.

Usa data/field_rects.json (nombres completos + páginas) para resolver los
nombres cortos a los nombres jerárquicos completos que pdftk requiere.
Verifica que cada nombre corto usado sea único; si no lo es, aborta.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

rows = json.loads((ROOT / "data" / "field_rects.json").read_text(encoding="utf-8"))

short_to_full: dict[str, str] = {}
for r in rows:
    short = r["name"].split(".")[-1]
    if short.startswith("PDF417BarCode1") or short.startswith("#pageSet") or short == "form1[0]":
        continue  # barcode calculado por JS de Adobe y contenedores: no se rellenan
    if short in short_to_full and short_to_full[short] != r["name"]:
        print(f"¡AMBIGUO! {short}: {short_to_full[short]} vs {r['name']}")
        sys.exit(1)
    short_to_full[short] = r["name"]

def F(short: str) -> dict:
    """Campo de texto: {field, }"""
    assert short in short_to_full, f"no encontrado: {short}"
    return {"field": short_to_full[short]}

def B(short: str, value: str) -> dict:
    """Checkbox: valor de exportación cuando está marcado."""
    assert short in short_to_full, f"no encontrado: {short}"
    return {"field": short_to_full[short], "value": value}

